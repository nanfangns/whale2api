CREATE TABLE IF NOT EXISTS gateway_api_keys (
    api_key TEXT PRIMARY KEY,
    name TEXT NOT NULL DEFAULT '',
    remark TEXT NOT NULL DEFAULT '',
    enabled INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'))
);

CREATE TABLE IF NOT EXISTS pool_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL DEFAULT '',
    token TEXT NOT NULL DEFAULT '',
    discarded INTEGER NOT NULL DEFAULT 0,
    discard_reason TEXT NOT NULL DEFAULT '',
    created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"')),
    mute_until TEXT NOT NULL DEFAULT '',
    device_id TEXT NOT NULL DEFAULT '',
    device_id_updated_at TEXT
);

CREATE TABLE IF NOT EXISTS pool_bindings (
    api_key TEXT NOT NULL REFERENCES gateway_api_keys (api_key) ON DELETE CASCADE,
    account_id BIGINT NOT NULL REFERENCES pool_accounts (id) ON DELETE CASCADE,
    position INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (api_key, account_id)
);

CREATE INDEX IF NOT EXISTS idx_pool_bindings_api_key_position
    ON pool_bindings (api_key, position);

CREATE TABLE IF NOT EXISTS pool_account_test_jobs (
    api_key TEXT PRIMARY KEY REFERENCES gateway_api_keys (api_key) ON DELETE CASCADE,
    status TEXT NOT NULL DEFAULT 'idle',
    total INTEGER NOT NULL DEFAULT 0,
    done INTEGER NOT NULL DEFAULT 0,
    ok_count INTEGER NOT NULL DEFAULT 0,
    failed_count INTEGER NOT NULL DEFAULT 0,
    skipped_count INTEGER NOT NULL DEFAULT 0,
    results TEXT NOT NULL DEFAULT '[]',
    updated_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'))
);
